module.exports = {
  name: 'poor_complexion',
  title: '气色差/面色不好',
  kind: 'symptom',
  // 「面色萎黄」原来也在本节点的词表里，但它同时被 face_yellow（面色萎黄）命中，
  // 于是「面色萎黄」的病人会同时点亮「气色差」——而「气色差」在大承气汤、抵当汤、
  // 桃核承气汤里是当「虚证，不可峻下/破血」用的，结果瘀血实证反而被排除掉了
  // （《经方实验录》抵当汤证其一：面色萎黄 + 少腹微胀，正是干血劳）。
  // 所以「面色萎黄」只留给 face_yellow，「气色差」只管真正的气血不足那一层。
  trigger(text) { return ['气色差', '面色不好', '脸色差', '面青', '面白无华', '没血色', '脸色苍白', '面色青灰', '气虚', '面目青', '脸色发青'].some(k => text.includes(k)) },
  negate(text) { return ['气色好', '面色红润', '有血色', '脸色不错'].some(k => text.includes(k)) },
  ask: '是不是气色不好，脸色发白发青、没血色？'
}
