module.exports = {
  name: 'lower_back_pain',
  title: '腰痛',
  kind: 'symptom',
  // 为什么单独建：「腰」这一带原来只有「腰酸」「腰冷」「腰腿酸困」，
  // 没有「痛」。第 35 条麻黄汤证明写「身疼腰痛」，肾著、八味肾气丸也都有腰痛，
  // 结果这些条文里的「腰痛」全被 yaosuan（腰酸）吃掉了——
  // 而 yaosuan 的 trigger 里原本就有 '腰痛'，于是「腰痛」会一路点亮
  // 「肾精血虚 → 补肾精血」。这里把「酸」和「痛」分开，各问一句。
  trigger(text) { return ['腰痛', '腰疼', '腰背痛', '腰背疼痛', '腰胀痛', '腰刺痛',
    '腰痛如折', '腰重痛', '腰痛得厉害', '腰弯不下去', '腰伸不直', '腰不能转侧',
    '腰像断了', '腰像要断'].some(k => text.includes(k)) },
  ask: '是不是腰这里疼？（不是酸软，是痛）'
}
